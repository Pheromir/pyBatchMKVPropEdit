"""Writes requirements-build.txt: every package the release build installs, with exact version and hashes.

The release workflow installs it with `pip install --require-hashes`, so a build gets exactly these files and
stops if one of them differs. The versions are the ones installed in the current environment (.venv), i.e. the
ones the program was tested with. Run it after updating a dependency:

    .venv\\Scripts\\python tools\\lock_build_requirements.py

The dependency tree is read from the installed packages and evaluated separately for Windows and Linux (pip
cannot do that for another system: it evaluates "platform_system" markers for the running one). The hashes of
all files of each version come from PyPI, so the script needs internet access. It stops if a package has no
wheel for one of the build systems.
"""

from __future__ import annotations

import json
import re
import sys
import tomllib
import urllib.request
from importlib import metadata
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name, parse_wheel_filename

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "requirements-build.txt"
PYTHON = (3, 14)
MAX_GLIBC = 35  # Ubuntu 22.04 in the release workflow
ENVIRONMENTS = {
    "win32": {"sys_platform": "win32", "platform_system": "Windows", "os_name": "nt", "platform_machine": "AMD64"},
    "linux": {"sys_platform": "linux", "platform_system": "Linux", "os_name": "posix", "platform_machine": "x86_64"},
}


def top_level() -> list[Requirement]:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    return [Requirement(s) for s in (*project["dependencies"], *project["optional-dependencies"]["dev"])]


def tree(env: dict[str, str]) -> dict[str, str]:
    """canonical name -> installed version of everything needed on that system."""
    env = {**default_environment(), **env, "python_version": "%d.%d" % PYTHON, "python_full_version": "%d.%d.0" % PYTHON}
    found: dict[str, str] = {}
    todo = [(r, frozenset()) for r in top_level()]
    while todo:
        req, extras = todo.pop()
        if req.marker and not any(req.marker.evaluate({**env, "extra": e}) for e in (extras or {""})):
            continue
        name = canonicalize_name(req.name)
        if name in found:
            continue
        try:
            found[name] = metadata.version(name)
        except metadata.PackageNotFoundError:
            sys.exit(f"{req.name} is needed on {env['sys_platform']} but not installed here; install it in .venv first")
        todo += [(Requirement(r), frozenset(req.extras)) for r in metadata.requires(name) or []]
    return found


def wheel_fits(filename: str, system: str) -> bool:
    if not filename.endswith(".whl"):
        return False
    _, _, _, tags = parse_wheel_filename(filename)
    for tag in tags:
        py = tag.interpreter
        if not (py in ("py3", f"cp{PYTHON[0]}{PYTHON[1]}") or (tag.abi == "abi3" and py.startswith("cp3"))):
            continue
        if tag.platform == "any":
            return True
        if system == "win32" and tag.platform == "win_amd64":
            return True
        if system == "linux":
            m = re.fullmatch(r"manylinux_2_(\d+)_x86_64", tag.platform)
            if (m and int(m.group(1)) <= MAX_GLIBC) or tag.platform in ("manylinux2014_x86_64", "manylinux1_x86_64"):
                return True
    return False


def pypi_files(name: str, version: str) -> list[dict]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as r:
        return json.load(r)["urls"]


def main() -> None:
    per_system = {system: tree(env) for system, env in ENVIRONMENTS.items()}
    names = sorted({n for found in per_system.values() for n in found})
    lines = [
        "# Generated by tools/lock_build_requirements.py: exact versions and hashes for the release build.",
        "# Install with: python -m pip install --require-hashes --only-binary=:all: -r requirements-build.txt",
    ]
    for name in names:
        systems = [s for s in ENVIRONMENTS if name in per_system[s]]
        version = per_system[systems[0]][name]
        files = pypi_files(name, version)
        for system in systems:
            if not any(wheel_fits(f["filename"], system) for f in files):
                sys.exit(f"{name} {version}: no wheel for {system} and Python {PYTHON[0]}.{PYTHON[1]}")
        marker = f' ; sys_platform == "{systems[0]}"' if len(systems) == 1 else ""
        digests = sorted({f["digests"]["sha256"] for f in files if f["filename"].endswith(".whl")})
        lines.append(f"{name}=={version}{marker} \\")
        lines += [f"    --hash=sha256:{d}" + (" \\" if i < len(digests) - 1 else "") for i, d in enumerate(digests)]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(names)} packages -> {OUT}")


if __name__ == "__main__":
    main()
